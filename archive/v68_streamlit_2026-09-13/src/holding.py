# H/홀딩/자바라처럼 보이는 문자열이 있어도 일반 주문으로 계속 처리한다.
# 품목표/계산 코드는 보존하며, 추후 다시 사용할 때만 이 플래그를 켠다.
HOLDING_FEATURE_ENABLED = False  # v63: 자동 판별을 완전히 중지

def is_holding_feature_item(item):
    """현재 item이 홀딩도어/홀딩 전용 부속인지 판별한다."""
    if not isinstance(item, dict):
        return False
    if item.get("_product_group") == "holding" or item.get("_holding_accessory"):
        return True
    if str(item.get("제품군") or "").strip() == "홀딩도어":
        return True
    raw = " ".join(str(item.get(k) or "") for k in
                   ("색상원문", "품목코드", "원문", "홀딩부속"))
    if not raw.strip():
        return False
    return bool(holding_accessory_from_text(raw) or holding_product_from_text(raw))

def apply_holding_feature_gate(order):
    """홀딩 자동판별 OFF 시 홀딩 분류를 제거하고 일반 주문으로 계속 처리한다.

    이전 v62처럼 행을 제외하지 않는다. 모델/파서가 실수로 홀딩으로 분류했더라도
    일반 블라인드 데이터로 되돌려 장부·작업지시서·EDI에 그대로 출력한다.
    """
    if HOLDING_FEATURE_ENABLED or not isinstance(order, dict):
        return 0
    changed = 0
    for item in order.get("items") or []:
        # 내부 holding 표식이 붙은 경우에만 제거한다. 원문에 H가 있다는 이유만으로
        # 새로 홀딩 판정을 하지 않는다.
        if not (item.get("_product_group") == "holding" or item.get("_holding_accessory")
                or str(item.get("제품군") or "").strip() == "홀딩도어"):
            continue
        item["제품군"] = "블라인드"
        # 과거 홀딩 분류 과정에서 붙은 예외표시도 전부 제거한다.
        # OFF 상태에서는 해당 행을 제외하지 않고 일반 주문으로 반드시 출력한다.
        exc = str(item.get("예외품목") or "").strip()
        if exc and ("홀딩" in exc or "자바라" in exc):
            item["예외품목"] = None
        item.pop("_product_group", None)
        item.pop("_ledger_prefix", None)
        item.pop("_holding_disabled", None)
        for key in list(item):
            if key.startswith("_holding_"):
                item.pop(key, None)
        item["홀딩방식"] = None
        item["홀딩레일"] = None
        item["홀딩상하로라"] = False
        item["홀딩부속"] = None
        item["홀딩부속색상"] = None
        changed += 1
    order.pop("_holding_disabled_count", None)
    return changed

